//! NightCut editor core: the non-destructive timeline model.
//!
//! A project is pure metadata (JSON). Source media is never modified while
//! editing; rendering happens only at export time (see `export-engine`).
//! Every edit is a small metadata change, which is why the editor stays
//! responsive even with 4K sources — playback uses proxies (media-engine).

use serde::{Deserialize, Serialize};
use thiserror::Error;

#[derive(Debug, Error, PartialEq)]
pub enum EditError {
    #[error("track not found: {0}")]
    TrackNotFound(String),
    #[error("clip not found: {0}")]
    ClipNotFound(String),
    #[error("invalid range: in={0} out={1}")]
    InvalidRange(f64, f64),
    #[error("split point {0} is outside the clip")]
    SplitOutside(f64),
}

pub type Result<T> = std::result::Result<T, EditError>;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum TrackKind {
    Video,
    Audio,
    Text,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Canvas {
    pub width: u32,
    pub height: u32,
    pub fps: u32,
}

impl Default for Canvas {
    /// 9:16 — the short-video default (TikTok / Reels / Shorts).
    fn default() -> Self {
        Self { width: 1080, height: 1920, fps: 30 }
    }
}

/// A video effect applied to a clip, in order. Each variant maps to a real
/// FFmpeg filter in export-engine and to a CSS-filter approximation in the
/// UI preview, so what you see while editing is what export renders.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum Effect {
    /// eq filter: brightness -1..1 (0 = neutral), contrast/saturation 0..3 (1 = neutral).
    Adjust { brightness: f64, contrast: f64, saturation: f64 },
    Grayscale,
    /// Vintage sepia, intensity 0..1.
    Sepia { intensity: f64 },
    /// Gaussian blur, sigma 0..50.
    Blur { sigma: f64 },
    /// Unsharp mask amount 0..2.
    Sharpen { amount: f64 },
    /// Vignette strength 0..1.
    Vignette { strength: f64 },
    /// Warm/cool shift: color temperature in Kelvin, 1000..11000 (6500 = neutral).
    Temperature { kelvin: f64 },
    Mirror,
    Invert,
    /// Video+audio fade in, seconds.
    FadeIn { duration: f64 },
    /// Video+audio fade out, seconds.
    FadeOut { duration: f64 },
    /// Play the clip backwards (rendered at export; the preview cannot
    /// reverse an HTML5 video element).
    Reverse,
    /// Green-screen keying: `color` is `#RRGGBB`, similarity/blend 0..1.
    /// The keyed area becomes transparent, composited over black at export.
    ChromaKey { color: String, similarity: f64, blend: f64 },
    /// Audio noise reduction (FFmpeg afftdn), strength 0..1.
    Denoise { strength: f64 },
}

/// One point of a speed curve (CapCut "Curve" speed). `at` is a fraction
/// 0..1 of the clip's source window; the segment starting at this point
/// plays at `speed`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SpeedPoint {
    pub at: f64,
    pub speed: f64,
}

/// A transform keyframe at `at` seconds into the clip's *played* duration.
/// Values interpolate linearly between keyframes at export (zoompan /
/// rotate / alpha expressions) and in the preview (CSS transforms).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Keyframe {
    pub at: f64,
    pub scale: f64,
    pub pos_x: f64,
    pub pos_y: f64,
    /// Degrees, clockwise.
    pub rotation: f64,
    pub opacity: f64,
}

impl Default for Keyframe {
    fn default() -> Self {
        Self { at: 0.0, scale: 1.0, pos_x: 0.0, pos_y: 0.0, rotation: 0.0, opacity: 1.0 }
    }
}

/// A transition *into* a clip from the previous clip on the same track
/// (CapCut applies transitions between clips). `kind` is an FFmpeg xfade
/// transition name: fade, fadeblack, fadewhite, dissolve, wipeleft,
/// wiperight, slideleft, slideright, circleopen, radial, smoothleft, …
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Transition {
    pub kind: String,
    pub duration: f64,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Clip {
    pub id: String,
    /// Source media path (empty for text clips).
    #[serde(default)]
    pub source: String,
    /// Proxy path generated by media-engine, used for preview playback.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub proxy: Option<String>,
    /// Trim in/out points inside the source, in seconds.
    pub in_sec: f64,
    pub out_sec: f64,
    /// Position on the timeline, in seconds.
    pub timeline_start: f64,
    #[serde(default = "default_speed")]
    pub speed: f64,
    #[serde(default = "default_volume")]
    pub volume: f64,
    /// Text content / styling for text-track clips.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub font_size: Option<u32>,
    /// Ordered effects for this clip (video clips only).
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub effects: Vec<Effect>,
    /// Transition into this clip from the previous clip (video track).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub transition_in: Option<Transition>,
    /// Text color for text clips, `#RRGGBB`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub text_color: Option<String>,
    /// Speed curve; when present it replaces the constant `speed`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub speed_curve: Option<Vec<SpeedPoint>>,
    /// Transform keyframes (video clips), sorted by `at` when used.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub keyframes: Vec<Keyframe>,
    /// Freeze-frame clip: hold the source frame at `in_sec` for this many
    /// seconds (the clip's played duration).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub freeze_duration: Option<f64>,
}

fn default_speed() -> f64 { 1.0 }
fn default_volume() -> f64 { 1.0 }

impl Clip {
    pub fn new(id: impl Into<String>, source: impl Into<String>, in_sec: f64, out_sec: f64, timeline_start: f64) -> Self {
        Self {
            id: id.into(), source: source.into(), proxy: None,
            in_sec, out_sec, timeline_start,
            speed: 1.0, volume: 1.0, text: None, font_size: None,
            effects: Vec::new(), transition_in: None, text_color: None,
            speed_curve: None, keyframes: Vec::new(), freeze_duration: None,
        }
    }
    pub fn text_clip(id: impl Into<String>, text: impl Into<String>, timeline_start: f64, duration: f64) -> Self {
        let mut c = Self::new(id, "", 0.0, duration, timeline_start);
        c.text = Some(text.into());
        c.font_size = Some(64);
        c
    }
    /// Played duration on the timeline after trimming and speed.
    /// A freeze clip lasts `freeze_duration`; a speed curve lasts the sum
    /// of its segments (source length / segment speed).
    pub fn duration(&self) -> f64 {
        if let Some(d) = self.freeze_duration {
            return d.max(0.0);
        }
        let source_len = (self.out_sec - self.in_sec).max(0.0);
        if let Some(curve) = &self.speed_curve {
            if !curve.is_empty() {
                let mut points = curve.clone();
                points.sort_by(|a, b| a.at.total_cmp(&b.at));
                let mut total = 0.0;
                for (i, p) in points.iter().enumerate() {
                    let start = p.at.clamp(0.0, 1.0);
                    let end = points.get(i + 1).map(|n| n.at.clamp(0.0, 1.0)).unwrap_or(1.0);
                    if end > start {
                        total += source_len * (end - start) / p.speed.max(0.01);
                    }
                }
                return total;
            }
        }
        (source_len / self.speed.max(0.01)).max(0.0)
    }
    pub fn timeline_end(&self) -> f64 {
        self.timeline_start + self.duration()
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Track {
    pub id: String,
    pub kind: TrackKind,
    #[serde(default)]
    pub clips: Vec<Clip>,
}

impl Track {
    pub fn new(id: impl Into<String>, kind: TrackKind) -> Self {
        Self { id: id.into(), kind, clips: Vec::new() }
    }
    fn clip_mut(&mut self, clip_id: &str) -> Result<&mut Clip> {
        self.clips.iter_mut().find(|c| c.id == clip_id)
            .ok_or_else(|| EditError::ClipNotFound(clip_id.to_string()))
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Project {
    pub version: u32,
    #[serde(default)]
    pub canvas: Canvas,
    #[serde(default)]
    pub tracks: Vec<Track>,
}

impl Default for Project {
    fn default() -> Self {
        Self {
            version: 1,
            canvas: Canvas::default(),
            tracks: vec![
                Track::new("track-video", TrackKind::Video),
                Track::new("track-audio", TrackKind::Audio),
                Track::new("track-text", TrackKind::Text),
            ],
        }
    }
}

impl Project {
    /// Total timeline duration: the latest clip end across all tracks.
    pub fn duration(&self) -> f64 {
        self.tracks.iter()
            .flat_map(|t| t.clips.iter().map(|c| c.timeline_end()))
            .fold(0.0, f64::max)
    }

    pub fn track_mut(&mut self, track_id: &str) -> Result<&mut Track> {
        self.tracks.iter_mut().find(|t| t.id == track_id)
            .ok_or_else(|| EditError::TrackNotFound(track_id.to_string()))
    }

    pub fn add_clip(&mut self, track_id: &str, clip: Clip) -> Result<()> {
        // Zero-length source windows are only valid for freeze-frame clips.
        if clip.out_sec <= clip.in_sec && clip.text.is_none() && clip.freeze_duration.is_none() {
            return Err(EditError::InvalidRange(clip.in_sec, clip.out_sec));
        }
        let track = self.track_mut(track_id)?;
        track.clips.push(clip);
        track.clips.sort_by(|a, b| a.timeline_start.total_cmp(&b.timeline_start));
        Ok(())
    }

    pub fn remove_clip(&mut self, track_id: &str, clip_id: &str) -> Result<Clip> {
        let track = self.track_mut(track_id)?;
        let pos = track.clips.iter().position(|c| c.id == clip_id)
            .ok_or_else(|| EditError::ClipNotFound(clip_id.to_string()))?;
        Ok(track.clips.remove(pos))
    }

    /// Move a clip along the timeline (clamped to >= 0).
    pub fn move_clip(&mut self, track_id: &str, clip_id: &str, new_start: f64) -> Result<()> {
        let track = self.track_mut(track_id)?;
        track.clip_mut(clip_id)?.timeline_start = new_start.max(0.0);
        track.clips.sort_by(|a, b| a.timeline_start.total_cmp(&b.timeline_start));
        Ok(())
    }

    /// Trim a clip: new in/out are source seconds, the timeline position of
    /// the clip start shifts by the change in `in_sec` is left to the caller
    /// in the UI layer; the core keeps the anchor at `timeline_start`.
    pub fn trim_clip(&mut self, track_id: &str, clip_id: &str, in_sec: f64, out_sec: f64) -> Result<()> {
        if out_sec <= in_sec {
            return Err(EditError::InvalidRange(in_sec, out_sec));
        }
        let clip = self.track_mut(track_id)?.clip_mut(clip_id)?;
        clip.in_sec = in_sec.max(0.0);
        clip.out_sec = out_sec;
        Ok(())
    }

    /// Split a clip at an absolute timeline time. Returns the new clip's id.
    pub fn split_clip(&mut self, track_id: &str, clip_id: &str, at_timeline: f64, new_id: impl Into<String>) -> Result<String> {
        let track = self.track_mut(track_id)?;
        let idx = track.clips.iter().position(|c| c.id == clip_id)
            .ok_or_else(|| EditError::ClipNotFound(clip_id.to_string()))?;
        let clip = &track.clips[idx];
        if at_timeline <= clip.timeline_start || at_timeline >= clip.timeline_end() {
            return Err(EditError::SplitOutside(at_timeline));
        }
        // Offset inside the source, accounting for speed.
        let source_offset = (at_timeline - clip.timeline_start) * clip.speed;
        let split_source = clip.in_sec + source_offset;

        let mut right = clip.clone();
        right.id = new_id.into();
        right.in_sec = split_source;
        right.timeline_start = at_timeline;
        // A split invalidates curve/freeze semantics (their fractions and
        // held frames refer to the whole clip) — both halves fall back to
        // the clip's constant speed.
        right.speed_curve = None;
        right.freeze_duration = None;
        right.keyframes.clear();

        let left = &mut track.clips[idx];
        left.out_sec = split_source;
        left.speed_curve = None;
        left.freeze_duration = None;
        left.keyframes.clear();

        let right_id = right.id.clone();
        track.clips.insert(idx + 1, right);
        Ok(right_id)
    }
}

/// Undo/redo history over immutable project snapshots.
/// Snapshot-based on purpose: edits are metadata-only, so a snapshot is
/// cheap (no media data is ever copied).
#[derive(Debug, Default)]
pub struct History {
    undo: Vec<Project>,
    redo: Vec<Project>,
    limit: usize,
}

impl History {
    pub fn new(limit: usize) -> Self {
        Self { undo: Vec::new(), redo: Vec::new(), limit }
    }
    /// Call with the state *before* applying an edit.
    pub fn push(&mut self, before: Project) {
        self.undo.push(before);
        if self.undo.len() > self.limit { self.undo.remove(0); }
        self.redo.clear();
    }
    pub fn undo(&mut self, current: Project) -> Option<Project> {
        let prev = self.undo.pop()?;
        self.redo.push(current);
        Some(prev)
    }
    pub fn redo(&mut self, current: Project) -> Option<Project> {
        let next = self.redo.pop()?;
        self.undo.push(current);
        Some(next)
    }
    pub fn can_undo(&self) -> bool { !self.undo.is_empty() }
    pub fn can_redo(&self) -> bool { !self.redo.is_empty() }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn project_with_clip() -> Project {
        let mut p = Project::default();
        p.add_clip("track-video", Clip::new("c1", "a.mp4", 1.0, 9.0, 0.0)).unwrap();
        p
    }

    #[test]
    fn duration_and_timeline_end() {
        let p = project_with_clip();
        assert_eq!(p.duration(), 8.0);
    }

    #[test]
    fn split_at_middle() {
        let mut p = project_with_clip();
        let new_id = p.split_clip("track-video", "c1", 3.0, "c2").unwrap();
        assert_eq!(new_id, "c2");
        let track = &p.tracks[0];
        assert_eq!(track.clips.len(), 2);
        assert_eq!(track.clips[0].out_sec, 4.0); // 1.0 in + 3.0 offset
        assert_eq!(track.clips[1].in_sec, 4.0);
        assert_eq!(track.clips[1].timeline_start, 3.0);
        assert_eq!(p.duration(), 8.0);
    }

    #[test]
    fn split_outside_is_an_error() {
        let mut p = project_with_clip();
        assert!(p.split_clip("track-video", "c1", 99.0, "c2").is_err());
        assert!(p.split_clip("track-video", "c1", 0.0, "c2").is_err());
    }

    #[test]
    fn split_respects_speed() {
        let mut p = Project::default();
        let mut c = Clip::new("c1", "a.mp4", 0.0, 10.0, 0.0);
        c.speed = 2.0;
        p.add_clip("track-video", c).unwrap();
        p.split_clip("track-video", "c1", 2.0, "c2").unwrap();
        // 2s on the timeline at 2x = 4s of source consumed.
        assert_eq!(p.tracks[0].clips[0].out_sec, 4.0);
        assert_eq!(p.duration(), 5.0);
    }

    #[test]
    fn trim_validates_range() {
        let mut p = project_with_clip();
        assert!(p.trim_clip("track-video", "c1", 5.0, 5.0).is_err());
        p.trim_clip("track-video", "c1", 2.0, 6.0).unwrap();
        assert_eq!(p.duration(), 4.0);
    }

    #[test]
    fn move_clamps_to_zero() {
        let mut p = project_with_clip();
        p.move_clip("track-video", "c1", -4.0).unwrap();
        assert_eq!(p.tracks[0].clips[0].timeline_start, 0.0);
        p.move_clip("track-video", "c1", 2.5).unwrap();
        assert_eq!(p.duration(), 10.5);
    }

    #[test]
    fn undo_redo_roundtrip() {
        let mut history = History::new(50);
        let mut p = project_with_clip();
        history.push(p.clone());
        p.split_clip("track-video", "c1", 3.0, "c2").unwrap();
        assert_eq!(p.tracks[0].clips.len(), 2);
        p = history.undo(p).unwrap();
        assert_eq!(p.tracks[0].clips.len(), 1);
        p = history.redo(p).unwrap();
        assert_eq!(p.tracks[0].clips.len(), 2);
    }

    #[test]
    fn effects_roundtrip_and_survive_split() {
        let mut p = Project::default();
        let mut c = Clip::new("c1", "a.mp4", 0.0, 8.0, 0.0);
        c.effects = vec![
            Effect::Adjust { brightness: 0.1, contrast: 1.2, saturation: 0.9 },
            Effect::Blur { sigma: 6.0 },
            Effect::FadeOut { duration: 0.5 },
        ];
        p.add_clip("track-video", c).unwrap();
        let json = serde_json::to_string(&p).unwrap();
        let back: Project = serde_json::from_str(&json).unwrap();
        assert_eq!(p, back);
        let mut p = back;
        p.split_clip("track-video", "c1", 4.0, "c2").unwrap();
        assert_eq!(p.tracks[0].clips[1].effects.len(), 3);
    }

    #[test]
    fn speed_curve_duration_is_segment_sum() {
        let mut c = Clip::new("c1", "a.mp4", 0.0, 10.0, 0.0);
        c.speed_curve = Some(vec![
            SpeedPoint { at: 0.0, speed: 1.0 },
            SpeedPoint { at: 0.5, speed: 2.0 },
        ]);
        // 5s at 1x + 5s at 2x = 5 + 2.5
        assert_eq!(c.duration(), 7.5);
    }

    #[test]
    fn freeze_duration_wins() {
        let mut c = Clip::new("c1", "a.mp4", 3.0, 3.0, 0.0);
        c.freeze_duration = Some(2.0);
        assert_eq!(c.duration(), 2.0);
    }

    #[test]
    fn json_roundtrip() {
        let p = project_with_clip();
        let json = serde_json::to_string(&p).unwrap();
        let back: Project = serde_json::from_str(&json).unwrap();
        assert_eq!(p, back);
    }
}
